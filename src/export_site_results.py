"""Parse the 30-seed run logs and write site/results.js for the project site.

Same logs make_pareto_plot.py reads. Any log that is missing or still
mid-run is simply left out — the site shows an "awaiting run" state for
that condition instead of a chart.

Optional: a per-epoch log from `python -m src.train_adaptive_alpha` fills
the alpha-trajectory chart.

  python -m src.export_site_results
  python -m src.export_site_results --trajectory /tmp/adaptive_single.log
"""
import argparse
import json
import os
import re
from datetime import date

BASELINE_LOG = "/tmp/baseline_30.log"
FIXED_LOG = "/tmp/fixed_30.log"
ADAPTIVE_LOG = "/tmp/adaptive_30.log"
OUT_PATH = "site/results.js"

# matches baseline ("seed=0: acc=...") and adaptive ("seed 0: acc=... alpha_deo=...")
SEED_LINE = re.compile(
    r"^seed[= ](\d+): acc=([\d.]+) deo=([\d.]+) dao=([\d.]+)"
    r"(?: alpha_deo=([\d.]+) alpha_dao=([\d.]+))?"
)
FIXED_LINE = re.compile(r"^alpha=([\d.]+) seed=(\d+): acc=([\d.]+) deo=([\d.]+) dao=([\d.]+)")
EPOCH_LINE = re.compile(
    r"^epoch (\d+)\s+p_loss=[-\d.]+\s+acc=([\d.]+)\s+deo=([\d.]+)\s+dao=([\d.]+)"
    r"\s+alpha_deo=([\d.]+)\s+alpha_dao=([\d.]+)"
)


def _empty():
    return {"acc": [], "deo": [], "dao": []}


def parse_seed_log(path: str) -> dict:
    out = _empty()
    if not os.path.exists(path):
        return out
    with open(path) as f:
        for line in f:
            m = SEED_LINE.match(line)
            if m:
                out["acc"].append(float(m.group(2)))
                out["deo"].append(float(m.group(3)))
                out["dao"].append(float(m.group(4)))
                if m.group(5) is not None:
                    out.setdefault("alpha_deo", []).append(float(m.group(5)))
                    out.setdefault("alpha_dao", []).append(float(m.group(6)))
    return out


def parse_fixed_log(path: str) -> dict:
    by_alpha = {}
    if not os.path.exists(path):
        return by_alpha
    with open(path) as f:
        for line in f:
            m = FIXED_LINE.match(line)
            if m:
                d = by_alpha.setdefault(float(m.group(1)), _empty())
                d["acc"].append(float(m.group(3)))
                d["deo"].append(float(m.group(4)))
                d["dao"].append(float(m.group(5)))
    return by_alpha


def parse_trajectory(path: str):
    if not path or not os.path.exists(path):
        return None
    rows = []
    with open(path) as f:
        for line in f:
            m = EPOCH_LINE.match(line)
            if m:
                rows.append({
                    "epoch": int(m.group(1)),
                    "acc": float(m.group(2)),
                    "deo": float(m.group(3)),
                    "dao": float(m.group(4)),
                    "alpha_deo": float(m.group(5)),
                    "alpha_dao": float(m.group(6)),
                })
    return rows or None


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--baseline", default=BASELINE_LOG)
    parser.add_argument("--fixed", default=FIXED_LOG)
    parser.add_argument("--adaptive", default=ADAPTIVE_LOG)
    parser.add_argument("--trajectory", default=None)
    parser.add_argument("--out", default=OUT_PATH)
    args = parser.parse_args()

    fixed = parse_fixed_log(args.fixed)
    conditions = [{"id": "baseline", "label": "Baseline", "seeds": parse_seed_log(args.baseline)}]
    for alpha in [0.5, 1.0, 2.0]:
        conditions.append({
            "id": f"fixed-{alpha:g}",
            "label": f"Fixed α = {alpha:g}",
            "seeds": fixed.get(alpha, _empty()),
        })
    conditions.append({"id": "adaptive", "label": "Adaptive α", "seeds": parse_seed_log(args.adaptive)})

    payload = {
        "updated": date.today().isoformat(),
        "conditions": conditions,
        "trajectory": parse_trajectory(args.trajectory),
    }

    with open(args.out, "w") as f:
        f.write("// Generated by `python -m src.export_site_results` — re-run after each sweep.\n")
        f.write("// Hand-edit `headline` and `figures` in site/content.js, not here.\n")
        f.write("window.RESULTS = ")
        json.dump(payload, f, indent=2)
        f.write(";\n")

    for c in conditions:
        print(f"{c['label']:<14} n={len(c['seeds']['acc'])}")
    print(f"trajectory: {len(payload['trajectory'] or [])} epochs")
    print(f"Saved: {args.out}")


if __name__ == "__main__":
    main()
